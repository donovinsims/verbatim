import { TranscriptError } from "./errors";
import { fetchResponse, readLimited } from "./http";
import { countWords, flattenCues } from "./time";
import type { Cue, TranscriptResult } from "./types";

const API_URL = "https://transcriptapi.com/api/v2/youtube/transcript";
const RESPONSE_LIMIT = 8 * 1024 * 1024;

type TranscriptSegment = {
  text?: unknown;
  start?: unknown;
  duration?: unknown;
};

type TranscriptApiResponse = {
  transcript?: TranscriptSegment[] | string;
  language?: unknown;
  title?: unknown;
  author_name?: unknown;
  duration?: unknown;
};

export async function fetchTranscriptApi(
  videoId: string,
  sourceUrl: string,
): Promise<TranscriptResult> {
  const apiKey = process.env.TRANSCRIPTAPI_API_KEY?.trim();
  if (!apiKey) {
    throw new TranscriptError(
      "provider_unavailable",
      "YouTube captions could not be fetched, and the hosted transcript fallback is not configured.",
      "Set TRANSCRIPTAPI_API_KEY in the server environment to enable the YouTube fallback.",
    );
  }

  const url = new URL(API_URL);
  url.searchParams.set("video_url", videoId);
  url.searchParams.set("format", "json");
  url.searchParams.set("include_timestamp", "true");
  url.searchParams.set("send_metadata", "true");

  const response = await fetchResponse(url.toString(), {
    timeoutMs: 25_000,
    headers: { Authorization: `Bearer ${apiKey}` },
    accept: "application/json",
  });

  if (response.status === 404) {
    throw new TranscriptError(
      "no_transcript",
      "The hosted transcript service found no available captions for this video.",
    );
  }
  if (response.status === 401 || response.status === 403) {
    throw new TranscriptError(
      "provider_unavailable",
      "The hosted transcript service rejected its API key.",
      "Check the TRANSCRIPTAPI_API_KEY server setting.",
    );
  }
  if (response.status === 402) {
    throw new TranscriptError(
      "provider_unavailable",
      "The hosted transcript service has used its available monthly credits.",
      "Check the provider plan and monthly credit balance. Automatic top-ups are not configured by Verbatim.",
    );
  }
  if (response.status === 429) {
    throw new TranscriptError(
      "rate_limited",
      "The hosted transcript service is rate-limiting requests. Try again later.",
    );
  }
  if (!response.ok) {
    throw new TranscriptError(
      "network",
      `The hosted transcript service returned HTTP ${response.status}.`,
    );
  }

  let payload: TranscriptApiResponse;
  try {
    const bytes = await readLimited(response, RESPONSE_LIMIT);
    payload = JSON.parse(new TextDecoder().decode(bytes)) as TranscriptApiResponse;
  } catch (err) {
    if (err instanceof TranscriptError) throw err;
    throw new TranscriptError("network", "The hosted transcript service returned invalid JSON.");
  }

  const cues = toCues(payload.transcript);
  if (!cues.length) {
    throw new TranscriptError(
      "no_transcript",
      "The hosted transcript service returned no caption segments.",
    );
  }

  const text = flattenCues(cues);
  const language = asString(payload.language);
  const durationSeconds = asFiniteNumber(payload.duration);
  return {
    kind: "transcript",
    title: asString(payload.title) || `YouTube ${videoId}`,
    author: asString(payload.author_name),
    durationMs:
      durationSeconds !== undefined && durationSeconds > 0
        ? durationSeconds * 1000
        : cues[cues.length - 1]?.endMs,
    source: "youtube",
    sourceUrl,
    canonicalUrl: `https://www.youtube.com/watch?v=${videoId}`,
    language,
    isAutoGenerated: language?.toLowerCase().startsWith("asr-") ?? false,
    cues,
    text,
    wordCount: countWords(text),
    fetchedAt: new Date().toISOString(),
  };
}

function toCues(input: TranscriptApiResponse["transcript"]): Cue[] {
  if (typeof input === "string") {
    const text = input.trim();
    return text ? [{ startMs: 0, endMs: 1000, text }] : [];
  }
  if (!Array.isArray(input)) return [];

  return input.flatMap((segment, index) => {
    const text = asString(segment.text)?.trim();
    if (!text) return [];

    const startSeconds = asFiniteNumber(segment.start) ?? 0;
    const startMs = Math.max(0, Math.round(startSeconds * 1000));
    const durationSeconds = asFiniteNumber(segment.duration);
    const nextStartSeconds = asFiniteNumber(input[index + 1]?.start);
    const endMs =
      durationSeconds !== undefined && durationSeconds > 0
        ? startMs + Math.round(durationSeconds * 1000)
        : nextStartSeconds !== undefined && nextStartSeconds * 1000 > startMs
          ? Math.round(nextStartSeconds * 1000)
          : startMs + 1000;

    return [{ startMs, endMs: Math.max(startMs + 1, endMs), text }];
  });
}

function asString(value: unknown): string | undefined {
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function asFiniteNumber(value: unknown): number | undefined {
  const number =
    typeof value === "number" ? value : typeof value === "string" ? Number(value) : NaN;
  return Number.isFinite(number) && number >= 0 ? number : undefined;
}
