import { afterEach, describe, expect, it, vi } from "vitest";
import { fetchTranscriptApi } from "./transcript-api";

describe("fetchTranscriptApi", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
    vi.unstubAllEnvs();
  });

  it("maps timestamped segments and metadata to a YouTube transcript", async () => {
    vi.stubEnv("TRANSCRIPTAPI_API_KEY", "test-secret");
    const fetchMock = vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = new URL(String(input));
      expect(url.origin + url.pathname).toBe("https://transcriptapi.com/api/v2/youtube/transcript");
      expect(url.searchParams.get("video_url")).toBe("jNQXAC9IVRw");
      expect(url.searchParams.get("format")).toBe("json");
      expect(url.searchParams.get("include_timestamp")).toBe("true");
      expect(url.searchParams.get("send_metadata")).toBe("true");
      expect(new Headers(init?.headers).get("authorization")).toBe("Bearer test-secret");
      return new Response(
        JSON.stringify({
          transcript: [
            { text: "Hello there", start: 0, duration: 1.25 },
            { text: "Welcome back", start: 1.25, duration: 0.75 },
          ],
          language: "en",
          title: "Sample video",
          author_name: "Sample channel",
          duration: 2,
        }),
        { status: 200, headers: { "content-type": "application/json" } },
      );
    });
    vi.stubGlobal("fetch", fetchMock);

    const result = await fetchTranscriptApi("jNQXAC9IVRw", "https://youtu.be/jNQXAC9IVRw");

    expect(result).toMatchObject({
      kind: "transcript",
      title: "Sample video",
      author: "Sample channel",
      durationMs: 2000,
      source: "youtube",
      sourceUrl: "https://youtu.be/jNQXAC9IVRw",
      canonicalUrl: "https://www.youtube.com/watch?v=jNQXAC9IVRw",
      language: "en",
      isAutoGenerated: false,
      text: "Hello there\nWelcome back",
      wordCount: 4,
    });
    expect(result.cues).toEqual([
      { text: "Hello there", startMs: 0, endMs: 1250 },
      { text: "Welcome back", startMs: 1250, endMs: 2000 },
    ]);
  });

  it("fails clearly when the server key is missing", async () => {
    vi.stubEnv("TRANSCRIPTAPI_API_KEY", "");
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);

    await expect(
      fetchTranscriptApi("jNQXAC9IVRw", "https://youtu.be/jNQXAC9IVRw"),
    ).rejects.toMatchObject({
      code: "provider_unavailable",
      message: expect.stringContaining("not configured"),
    });
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it.each([
    [404, "no_transcript"],
    [401, "provider_unavailable"],
    [403, "provider_unavailable"],
    [402, "provider_unavailable"],
    [429, "rate_limited"],
    [503, "network"],
  ] as const)("maps provider HTTP %i to %s", async (status, code) => {
    vi.stubEnv("TRANSCRIPTAPI_API_KEY", "test-secret");
    vi.stubGlobal(
      "fetch",
      vi.fn(async () => new Response("{}", { status })),
    );

    await expect(
      fetchTranscriptApi("jNQXAC9IVRw", "https://youtu.be/jNQXAC9IVRw"),
    ).rejects.toMatchObject({ code });
  });

  it("maps provider network failures to a transcript-service network error", async () => {
    vi.stubEnv("TRANSCRIPTAPI_API_KEY", "test-secret");
    vi.stubGlobal(
      "fetch",
      vi.fn(async () => {
        throw new Error("network down");
      }),
    );

    await expect(
      fetchTranscriptApi("jNQXAC9IVRw", "https://youtu.be/jNQXAC9IVRw"),
    ).rejects.toMatchObject({
      code: "network",
      message: expect.stringContaining("network down"),
    });
  });
});
